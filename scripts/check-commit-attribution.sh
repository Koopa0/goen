#!/usr/bin/env bash
# Git messages are read as data; none of their text becomes a shell command.
set -euo pipefail

if [[ $# != 2 || ! $1 =~ ^[0-9a-f]{40}$ || ! $2 =~ ^[0-9a-f]{40}$ ]]; then
  echo 'commit-attribution: two full commit SHAs are required' >&2
  exit 2
fi
base=$1
head=$2
git rev-parse --verify "$head^{commit}" >/dev/null
if [[ $base == 0000000000000000000000000000000000000000 ]]; then
  commits=$(git rev-list "$head")
else
  if git rev-parse --verify "$base^{commit}" >/dev/null 2>&1; then
    commits=$(git rev-list "$base..$head")
  else
    commits=$(git rev-list "$head")
  fi
fi

# What counts as AI attribution is defined here and nowhere else. Every entry
# is an extended regular expression matched case-insensitively. A human
# co-author is credited with a well-formed Co-authored-by trailer; the rest of
# this file exists to refuse the same trailer when it names an AI tool.
#
# Whole message. The first four entries and co-committed-by are the floor the
# check had before human co-authors were allowed: never narrow them. The third
# also rejects a trailer whose name begins with the letters of one of its tool
# words, so "Co-authored-by: Claude Monet <...>" and "Claudette Colbert" are
# rejected on purpose; a name that only contains the word ("Jean-Claude Van
# Damme") is accepted.
ai_message_patterns=(
  '(cursor|codex|claude|copilot|chatgpt)[[:space:]]+agent'
  'cursoragent@'
  '(written|generated|authored|assisted)[[:space:]-]+by[[:space:]:-]+(cursor|codex|claude|copilot|chatgpt|openai|anthropic)'
  'app/cursor'
  'co[ -]committed[ -]by[[:space:]]*:'
  # "Generated with [Tool](url)" or "Generated by Tool" at the start of a line
  '^[[:space:]>*_-]*generated[[:space:]]+(with|by|using)[[:space:]]+(\[|(the[[:space:]]+)?(claude|cursor|codex|copilot|chatgpt|gpt|openai|anthropic|gemini|grok|aider|devin|windsurf|codeium))'
  '^[[:space:]]*assisted-by[[:space:]]*:'
  # robot-emoji attribution lines
  '🤖|:robot:'
  # AI tool session and product links
  'claude\.ai/(code|chat)|claude\.com/claude-code|anthropic\.com/claude-code|chatgpt\.com|chat\.openai\.com|cursor\.com/(agents|background)|gemini\.google\.com|grok\.com|github\.com/copilot|copilot-swe-agent'
  '^[[:space:]]*claude-session[[:space:]]*:'
  # every address at an AI vendor, the Copilot noreply address, and GitHub bot
  # identities of AI tools
  '@(anthropic\.com|openai\.com|cursor\.com|cursor\.sh|aider\.chat|codeium\.com|windsurf\.com|windsurf\.ai|x\.ai)([^[:alnum:]-]|$)'
  'copilot@users\.noreply\.github\.com'
  '(claude|copilot|cursor|codex|chatgpt|openai|anthropic|gemini|grok|aider|devin|coderabbit|sourcery|qodo|codeium|windsurf)[a-z0-9-]*\[bot\]'
  # Any bot named on a line that claims credit. A bot named in a Signed-off-by
  # line (Dependabot's own commits end with one) claims nothing and is not
  # matched; only the AI bots above are refused there.
  '^[[:space:]]*(co[ -](authored|committed|developed)[ -]by|assisted-by)[[:space:]]*:.*\[bot\]'
)

# A trailer line "Key: Name <email>" whose Name is exactly an AI tool, optionally
# followed by a version, a parenthesised model, or one of agent/bot/code/ai/cli.
# The name is matched whole so that a human with the same first name is not
# caught here.
ai_name_patterns=(
  '^[[:space:]]*[a-z][a-z-]*[[:space:]]*:[[:space:]]*(claude|claude code|cursor|cursor agent|codex|openai codex|copilot|github copilot|chatgpt|gemini|grok|aider|devin|windsurf|cody|amazon q)([[:space:]]+([0-9][^<]*|\([^<]*\)|ai|bot|agent|code|assistant|cli))*[[:space:]]*<'
)

# The only Co-authored-by line that is accepted: key and value on one line with
# no leading space, a non-empty name, and a single address.
human_trailer='^co-authored-by: [^<>]+ <[^<>[:space:]@]+@[^<>[:space:]@]+\.[^<>[:space:]@]+>[[:space:]]*$'
coauthor_key='co[ -]authored[ -]by[[:space:]]*:'
trailer_line='^[[:space:]]*[a-z][a-z-]*[[:space:]]*:[^<]*<[^>]*>'

join_patterns() {
  local IFS='|'
  printf '%s' "$*"
}
ai_message=$(join_patterns "${ai_message_patterns[@]}")
ai_name=$(join_patterns "${ai_name_patterns[@]}")

# find_lines PATTERN TEXT [GREP_FLAGS] puts the matching lines in $match and
# returns 0 on a match, 1 on none (-v selects the lines that do not match); any
# other grep status ends the run, so a broken detector cannot pass.
match=''
find_lines() {
  local detector_status=0
  match=$(printf '%s\n' "$2" | LC_ALL=C grep "${3:--iE}" -- "$1") || detector_status=$?
  if [[ $detector_status != 0 && $detector_status != 1 ]]; then
    echo 'commit-attribution: detector failed' >&2
    exit 2
  fi
  return "$detector_status"
}

status=0
for sha in $commits; do
  message=$(git log -1 --format=%B "$sha")
  rejected=0
  if find_lines "$ai_message" "$message"; then
    rejected=1
  elif find_lines "$trailer_line" "$message" && find_lines "$ai_name" "$match"; then
    rejected=1
  elif find_lines "$coauthor_key" "$message" && find_lines "$human_trailer" "$match" -ivE; then
    rejected=1
  fi
  if [[ $rejected == 1 ]]; then
    echo "commit-attribution: forbidden attribution in $sha" >&2
    status=1
  fi
done
if [[ $status != 0 ]]; then
  exit "$status"
fi
echo 'commit-attribution: PASS'
