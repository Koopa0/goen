package db_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestCommitAttributionRejectsMessagesAndUnknownRevisions(t *testing.T) {
	script, pathErr := filepath.Abs(filepath.Join("..", "..", "scripts", "check-commit-attribution.sh"))
	if pathErr != nil {
		t.Fatal(pathErr)
	}
	dir := t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.CommandContext(t.Context(), "git", args...) //nolint:gosec // Arguments are test-owned literals and commit messages passed as data, without a shell.
		cmd.Dir = dir
		output, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v: %s", args, err, output)
		}
		return strings.TrimSpace(string(output))
	}
	git("init", "-q")
	git("config", "user.name", "message-test")
	git("config", "user.email", "message-test@goen.invalid")
	git("config", "commit.gpgsign", "false")
	git("commit", "--allow-empty", "-qm", "test: clean base")
	base := git("rev-parse", "HEAD")
	for _, tc := range []struct {
		name    string
		message string
		wantRed bool
	}{
		{"clean", "fix: preserve the native form", false},
		{"coauthor", "fix: preserve the form\n\nCo-authored-by: Someone <person@example.com>", true},
		{"owner trailer", "fix: preserve the form\n\nCo-authored-by: Koopa <Koopa0@users.noreply.github.com>", true},
		{"case and spacing", "fix: preserve the form\n\n  CO-AUTHORED-BY : Someone <person@example.com>", true},
		{"inline attribution", "fix: preserve the form Co-authored-by: Someone", true},
		{"self identification", "fix: written by Cursor", true},
		{"agent identity", "fix: preserve the form\n\nCursor Agent", true},
		{"generated attribution", "fix: generated by Cursor", true},
		{"other generated attribution", "fix: generated by Codex", true},
		{"large message", "fix: preserve the form\n\nCo-authored-by: Someone\n" + strings.Repeat("body\n", 20000), true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			git("commit", "--allow-empty", "-qm", tc.message)
			head := git("rev-parse", "HEAD")
			cmd := exec.CommandContext(t.Context(), "bash", script, base, head) //nolint:gosec // Only the fixed repository script and test-owned commit SHAs execute.
			cmd.Dir = dir
			output, err := cmd.CombinedOutput()
			if (err != nil) != tc.wantRed {
				t.Fatalf("want red=%t, got %v: %s", tc.wantRed, err, output)
			}
			if tc.wantRed && !strings.Contains(string(output), "forbidden attribution") {
				t.Fatalf("not an attribution failure: %s", output)
			}
			base = head
		})
	}
	cmd := exec.CommandContext(t.Context(), "bash", script, strings.Repeat("f", 40), base) //nolint:gosec // The deliberately unknown SHA is test-owned input to a fixed script.
	cmd.Dir = dir
	if output, err := cmd.CombinedOutput(); err == nil {
		t.Fatalf("unknown revision passed: %s", output)
	}
	fixture := filepath.Join(dir, "failing-grep.sh")
	if err := os.WriteFile(fixture, []byte("grep() { return 2; }\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	git("commit", "--allow-empty", "-qm", "test: clean detector input")
	cmd = exec.CommandContext(t.Context(), "bash", script, base, git("rev-parse", "HEAD")) //nolint:gosec // A fixed script gets test-owned SHAs and a test-owned failing detector.
	cmd.Dir = dir
	cmd.Env = append(cmd.Environ(), "BASH_ENV="+fixture)
	output, err := cmd.CombinedOutput()
	if err == nil || !strings.Contains(string(output), "detector failed") {
		t.Fatalf("detector error must fail closed, got %v: %s", err, output)
	}
}
