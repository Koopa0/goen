package repocheck_test

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

// minSourcePackages is the floor under the walk: main has 102 packages, so a
// walk that finds far fewer has stopped looking at the repository.
const minSourcePackages = 95

// TestEveryPackageDocNamesItsPackage holds every package to the Go convention
// for its package comment (go.dev/doc/comment#package): the comment exists, and
// its first sentence begins "Package <name>", or "Command <name>" for a main
// package. go doc, pkg.go.dev and every package listing show that sentence.
//
// A generated file must not carry a package comment at all. go/doc joins the
// package comments of every file in file-name order, so a header such as
// templ's "// templ: version: …" directly above the package clause, in a
// *_templ.go that sorts before the hand-written file, became the summary of 23
// packages. The Makefile passes -include-version=false to stop it, and this
// test fails if a lost flag or a generator upgrade brings the comment back.
func TestEveryPackageDocNamesItsPackage(t *testing.T) {
	t.Parallel()
	root := repoRoot(t)
	dirs, err := goDirs(root, func(name string) bool {
		return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
	})
	if err != nil {
		t.Fatalf("walk the repository for Go packages: %v", err)
	}
	if len(dirs) < minSourcePackages {
		t.Fatalf("the walk found %d directories holding Go source, want at least %d: it has stopped looking at the repository", len(dirs), minSourcePackages)
	}
	for _, problem := range checkPackageDocs(root, dirs) {
		t.Error(problem)
	}
}

// checkPackageDocs returns what is wrong with the package comment of each
// directory in dirs. The comment that counts is the first one in file-name
// order among the hand-written files, which is the one go doc prints first.
func checkPackageDocs(root string, dirs []string) []string {
	var problems []string
	for _, dir := range dirs {
		files, err := filepath.Glob(filepath.Join(root, filepath.FromSlash(dir), "*.go"))
		if err != nil {
			problems = append(problems, dir+": "+err.Error())
			continue
		}
		slices.Sort(files)
		var name, doc string
		for _, file := range files {
			if strings.HasSuffix(file, "_test.go") {
				continue
			}
			f, parseErr := parser.ParseFile(token.NewFileSet(), file, nil, parser.PackageClauseOnly|parser.ParseComments)
			if parseErr != nil {
				problems = append(problems, dir+": "+parseErr.Error())
				continue
			}
			name = f.Name.Name
			switch {
			case f.Doc == nil:
			case ast.IsGenerated(f):
				problems = append(problems, fmt.Sprintf("%s/%s: a generated file has a package comment, which go doc joins into the package's summary: %q", dir, filepath.Base(file), strings.TrimSpace(f.Doc.Text())))
			case doc == "":
				doc = f.Doc.Text()
			}
		}
		prefix := "Package " + name + " "
		if name == "main" {
			prefix = "Command " + path.Base(dir) + " "
		}
		if !strings.HasPrefix(doc, prefix) {
			problems = append(problems, fmt.Sprintf("%s: the package comment must begin %q, not %q", dir, strings.TrimSpace(prefix), firstLine(doc)))
		}
	}
	return problems
}

// TestCheckPackageDocs runs the check over fixture packages: each fault has a
// case that must report it, and the conventional comments must pass.
func TestCheckPackageDocs(t *testing.T) {
	t.Parallel()
	const generated = "// Code generated by templ - DO NOT EDIT.\n\n"
	for _, tc := range []struct {
		name  string
		files map[string]string
		want  string // a substring of the one problem; "" means none
	}{
		{"named", map[string]string{"shop/shop.go": "// Package shop sells.\npackage shop\n"}, ""},
		{"command", map[string]string{"cmd/shop/main.go": "// Command shop runs.\npackage main\n"}, ""},
		{"generated without a comment", map[string]string{
			"shop/a_templ.go": generated + "package shop\n",
			"shop/shop.go":    "// Package shop sells.\npackage shop\n",
		}, ""},
		{"missing", map[string]string{"shop/shop.go": "package shop\n"}, `not ""`},
		{"unnamed", map[string]string{"shop/shop.go": "// Sells things.\npackage shop\n"}, `not "Sells things."`},
		{"another package's name", map[string]string{"shop/shop.go": "// Package cart sells.\npackage shop\n"}, `not "Package cart sells."`},
		{"only a prefix of the name", map[string]string{"shop/shop.go": "// Package shopping sells.\npackage shop\n"}, `not "Package shopping sells."`},
		{"command named for the package", map[string]string{"cmd/shop/main.go": "// Package main runs.\npackage main\n"}, `begin "Command shop"`},
		{"generated comment", map[string]string{
			"shop/a_templ.go": generated + "// templ: version: v0.3.1070\npackage shop\n",
			"shop/shop.go":    "// Package shop sells.\npackage shop\n",
		}, "a generated file has a package comment"},
		{"generated file alone", map[string]string{"shop/a_templ.go": generated + "package shop\n"}, `not ""`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			dirs := map[string]bool{}
			for file, body := range tc.files {
				full := filepath.Join(root, filepath.FromSlash(file))
				if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
					t.Fatal(err)
				}
				dirs[path.Dir(file)] = true
			}
			got := checkPackageDocs(root, slices.Collect(maps.Keys(dirs)))
			switch {
			case tc.want == "" && len(got) != 0:
				t.Errorf("reported %q, want no problem", got)
			case tc.want != "" && (len(got) != 1 || !strings.Contains(got[0], tc.want)):
				t.Errorf("reported %q, want one problem containing %q", got, tc.want)
			}
		})
	}
}
