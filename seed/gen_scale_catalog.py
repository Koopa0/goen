#!/usr/bin/env python3
"""Generate disposable catalogue shapes for query-plan evidence.

Emits seed/scale_catalog_small.sql (~15 products, same shape as dev_catalog)
and seed/scale_catalog_large.sql (10,000 active products with skewed categories,
variants, reviews, images, Chinese/English terms and stock distributions).

Deterministic: the same scale always yields the same file bytes.
"""
import argparse
import pathlib
import shutil

SMALL_PRODUCTS = 15
LARGE_PRODUCTS = 10_000

BRANDS = [
    ("pixelight", "Pixelight"),
    ("aurora", "Aurora"),
    ("koto", "琴 Koto"),
    ("meridian", "Meridian"),
    ("nimbus", "Nimbus"),
]

CATS = [
    ("phones", "手機", "phone", None, 0),
    ("laptops", "筆電", "laptop", None, 1),
    ("tablets", "平板", "tablet", None, 2),
    ("audio", "耳機與音響", "headphones", None, 3),
    ("wearables", "穿戴裝置", "watch", None, 4),
    ("accessories", "周邊配件", "plug", None, 5),
    ("chargers", "充電與線材", "plug", "accessories", 0),
    ("cases", "保護殼與包", "shield", "accessories", 1),
]

# Skew weights over root categories (phones dominate).
ROOT_WEIGHTS = {
    "phones": 35,
    "laptops": 20,
    "tablets": 12,
    "audio": 15,
    "wearables": 8,
    "accessories": 10,
}
CHILD_OF = {
    "chargers": "accessories",
    "cases": "accessories",
}


def uid(n: int) -> str:
    return f"{n:08x}-0000-4000-8000-{n:012x}"


def write_small(path: pathlib.Path) -> None:
    src = path.parent / "dev_catalog.sql"
    shutil.copyfile(src, path)
    print(f"wrote {path}: {SMALL_PRODUCTS} products (dev catalogue copy)")


def write_large(path: pathlib.Path) -> None:
    out: list[str] = []

    def w(line: str = "") -> None:
        out.append(line)

    w("-- goen scale catalogue — large (10,000 products)")
    w("-- Generated by seed/gen_scale_catalog.py; disposable query-plan fixture.")
    w("BEGIN;")
    w("")

    brand_id = {slug: uid(100 + i) for i, (slug, _) in enumerate(BRANDS)}
    w("INSERT INTO brands (id, slug, name) VALUES")
    w(",\n".join(f"    ('{brand_id[s]}', '{s}', '{n}')" for s, n in BRANDS) + ";")
    w("")

    cat_id: dict[str, str] = {}
    for i, (slug, name, icon, parent, pos) in enumerate(CATS, 1):
        cat_id[slug] = uid(200 + i)
    w("INSERT INTO categories (id, parent_id, slug, name, icon_key, position) VALUES")
    rows = []
    for slug, name, icon, parent, pos in CATS:
        p = f"'{cat_id[parent]}'" if parent else "NULL"
        rows.append(f"    ('{cat_id[slug]}', {p}, '{slug}', '{name}', '{icon}', {pos})")
    w(",\n".join(rows) + ";")
    w("")

    # Flatten category weights to leaf categories used for products.
    leaf_weights: list[tuple[str, int]] = []
    for slug, weight in ROOT_WEIGHTS.items():
        children = [c for c, p in CHILD_OF.items() if p == slug]
        if children:
            each = max(weight // len(children), 1)
            for child in children:
                leaf_weights.append((child, each))
        else:
            leaf_weights.append((slug, weight))
    thresholds: list[tuple[str, int]] = []
    acc = 0
    for slug, weight in leaf_weights:
        acc += weight
        thresholds.append((slug, acc))

    w("-- 10,000 active products: skewed categories, bilingual names, mixed stock.")
    w("INSERT INTO products (id, brand_id, category_id, slug, name, name_en, summary, summary_en, status, published_at)")
    w("SELECT")
    w("    ('3' || lpad(gs::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    (ARRAY[" + ",".join(f"'{brand_id[s]}'::uuid" for s, _ in BRANDS) + "])[1 + (gs % " + str(len(BRANDS)) + ")],")
    w("    CASE")
    for slug, cutoff in thresholds:
        w(f"        WHEN (gs % 100) < {cutoff} THEN '{cat_id[slug]}'::uuid")
    w(f"        ELSE '{cat_id[leaf_weights[-1][0]]}'::uuid")
    w("    END,")
    w("    'scale-' || lpad(gs::text, 5, '0'),")
    w("    CASE WHEN gs % 4 = 0 THEN '量測商品 ' || gs::text ELSE 'Scale product ' || gs::text END,")
    w("    CASE WHEN gs % 4 = 0 THEN 'Scale product ' || gs::text ELSE '量測商品 ' || gs::text END,")
    w("    '量測摘要 ' || gs::text,")
    w("    'Scale summary ' || gs::text,")
    w("    'active',")
    w("    now() - ((gs % 365) || ' days')::interval")
    w("FROM generate_series(1, " + str(LARGE_PRODUCTS) + ") gs;")
    w("")

    w("-- One or two variants per product; every third product carries a markdown.")
    w("INSERT INTO product_variants (id, product_id, sku, price_cents, compare_at_price_cents, stock_quantity, safety_stock, position)")
    w("SELECT")
    w("    ('4' || lpad((gs * 10 + v)::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    ('3' || lpad(gs::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    'SC-' || lpad(gs::text, 5, '0') || '-' || v,")
    w("    500000 + (gs % 500) * 10000 + v * 50000,")
    w("    CASE WHEN gs % 3 = 0 THEN 600000 + (gs % 500) * 10000 + v * 50000 ELSE NULL END,")
    w("    CASE")
    w("        WHEN gs % 9 = 0 THEN 0")
    w("        WHEN gs % 5 = 2 AND v = 0 THEN 2")
    w("        ELSE 5 + (gs % 20)")
    w("    END,")
    w("    2,")
    w("    v")
    w("FROM generate_series(1, " + str(LARGE_PRODUCTS) + ") gs")
    w("CROSS JOIN generate_series(0, 1) v")
    w("WHERE v = 0 OR gs % 2 = 0;")
    w("")

    w("INSERT INTO product_images (id, product_id, storage_key, alt_text, alt_text_en, width, height, position)")
    w("SELECT")
    w("    ('5' || lpad(gs::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    ('3' || lpad(gs::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    'scale-' || lpad(gs::text, 5, '0') || '-01.webp',")
    w("    '量測商品 ' || gs::text || ' 商品照',")
    w("    'Scale product ' || gs::text || ' photo',")
    w("    1600, 1200, 0")
    w("FROM generate_series(1, " + str(LARGE_PRODUCTS) + ") gs;")
    w("")

    w("INSERT INTO product_reviews (id, product_id, user_id, rating, title, body, is_verified_purchase)")
    w("SELECT")
    w("    ('6' || lpad((gs * 3 + r)::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    ('3' || lpad(gs::text, 7, '0') || '-0000-4000-8000-000000000000')::uuid,")
    w("    NULL,")
    w("    3 + (r % 3),")
    w("    '量測評論 ' || gs::text || '-' || r::text,")
    w("    'Scale review body',")
    w("    false")
    w("FROM generate_series(1, " + str(LARGE_PRODUCTS) + ") gs")
    w("CROSS JOIN generate_series(0, 2) r")
    w("WHERE gs % 2 = 0 OR r = 0;")
    w("")

    # Checkout still needs shipping rows on a disposable database.
    w("INSERT INTO shipping_methods (id, code, position) VALUES")
    w("    ('ffff0001-0000-4000-8000-000000000001', 'home_delivery', 0),")
    w("    ('ffff0001-0000-4000-8000-000000000002', 'store_pickup', 1)")
    w("    ON CONFLICT DO NOTHING;")
    w("")
    w("INSERT INTO shipping_method_versions (id, method_id, name, carrier, fee_cents, free_over_cents) VALUES")
    w("    ('ffff0002-0000-4000-8000-000000000001', 'ffff0001-0000-4000-8000-000000000001', '宅配到府', '黑貓宅急便', 8000, 300000),")
    w("    ('ffff0002-0000-4000-8000-000000000002', 'ffff0001-0000-4000-8000-000000000002', '超商取貨', '7-ELEVEN', 6000, 300000)")
    w("    ON CONFLICT DO NOTHING;")
    w("")
    w("COMMIT;")
    w("")

    path.write_text("\n".join(out))
    print(f"wrote {path}: {LARGE_PRODUCTS} products")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "scale",
        choices=("small", "large", "all"),
        default="all",
        nargs="?",
        help="which fixture to emit (default: all)",
    )
    args = parser.parse_args()
    here = pathlib.Path(__file__).resolve().parent
    if args.scale in ("small", "all"):
        write_small(here / "scale_catalog_small.sql")
    if args.scale in ("large", "all"):
        write_large(here / "scale_catalog_large.sql")


if __name__ == "__main__":
    main()
