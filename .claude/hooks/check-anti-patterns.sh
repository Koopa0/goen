#!/usr/bin/env bash
# PreToolUse hook: Block creation of DDD-style / forbidden directories.
# Reads tool use JSON from stdin, checks if file_path contains forbidden dirs.
# Exit 2 with reason on stderr if matched, exit 0 otherwise.

# The runtime path is relative to this hook; the canonical gate also lints the helper.
# shellcheck disable=SC1091
source "$(dirname "$0")/parse-hook-input.sh"

input=$(cat)
file_path=$(parse_file_path "$input")

if [[ -z "$file_path" ]]; then
    exit 0
fi

# Make path relative to project root to avoid false positives from GOPATH /src/
project_root=$(cd "$(dirname "$0")/../.." && pwd)
relative_path="${file_path#"$project_root"/}"

# Paths outside this project are not governed by this hook: if the prefix
# strip changed nothing, the file lives in another repo (e.g. a GOPATH
# checkout whose path contains /src/).
if [[ "$relative_path" == "$file_path" && "$file_path" == /* ]]; then
    exit 0
fi

# List of forbidden directory patterns
forbidden=(
    "/services/"
    "/service/"
    "/repositories/"
    "/repository/"
    "/handlers/"
    "/handler/"
    "/controllers/"
    "/controller/"
    "/models/"
    "/model/"
    "/entities/"
    "/entity/"
    "/dto/"
    "/dtos/"
    "/mappers/"
    "/mapper/"
    "/factory/"
    "/factories/"
    "/domain/"
    "/infrastructure/"
    "/application/"
    "/presentation/"
    "/util/"
    "/utils/"
    "/helper/"
    "/helpers/"
    "/common/"
    "/shared/"
    "/base/"
    "/types/"
    "/src/"
    "/pkg/"
)

# Normalize: ensure relative path has leading / for consistent matching
normalized="/$relative_path"

for pattern in "${forbidden[@]}"; do
    if [[ "$normalized" == *"$pattern"* ]]; then
        dir_name=$(echo "$pattern" | tr -d '/')
        echo "BLOCKED: Forbidden directory '${dir_name}' detected in path '${relative_path}'. This project uses package-by-feature organization. Place code in a feature package under internal/ (e.g., internal/order/, internal/user/). See .claude/rules/package-organization.md." >&2
        exit 2
    fi
done

# Mock code generation is forbidden (rules/testing.md — mocks never).
# Catches //go:generate mockgen/mockery/moq/counterfeiter directives and
# committed MockGen output headers in Write/Edit content. Known gaps
# (accepted): generation run via Bash, generated files with scrubbed
# headers — depguard import deny + reviewers cover those.
if [[ "$file_path" == *.go ]] && command -v jq &>/dev/null; then
    content=$(printf '%s' "$input" | jq -r '.tool_input.content // .tool_input.new_string // empty' 2>/dev/null)
    if [[ -n "$content" ]] && printf '%s' "$content" | grep -qE '//go:generate .*(mockgen|mockery|moq |counterfeiter)|Code generated by (MockGen|mockery|moq|counterfeiter)'; then
        echo "BLOCKED: mock code generation detected in '${relative_path}'. Mock frameworks are forbidden — use real dependencies via testcontainers-go, or a hand-written fake for non-containerizable externals. See .claude/rules/testing.md § Test Doubles." >&2
        exit 2
    fi
fi

exit 0
