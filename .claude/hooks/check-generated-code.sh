#!/usr/bin/env bash
# PreToolUse hook: Block edits to generated code (sqlc, go generate).
# Exit 2 with reason on stderr if matched, exit 0 otherwise.

# The runtime path is relative to this hook; the canonical gate also lints the helper.
# shellcheck disable=SC1091
source "$(dirname "$0")/parse-hook-input.sh"

input=$(cat)
file_path=$(parse_file_path "$input")

if [[ -z "$file_path" ]]; then
    exit 0
fi

project_root=$(cd "$(dirname "$0")/../.." && pwd)
relative_path="${file_path#"$project_root"/}"

# GOEN: upstream blocks all of internal/db/, which in go-spec holds nothing but
# sqlc output. goen keeps its schema conformance suite in the same package —
# five hand-written *_integration_test.go files plus dbtest/ — so the block is
# narrowed to the three files sqlc actually writes. The generated-header check
# below is the backstop if sqlc ever emits a fourth.
case "$relative_path" in
    internal/db/db.go|internal/db/models.go|internal/db/query.sql.go)
        echo "BLOCKED: $relative_path is sqlc output. Change internal/*/query.sql or the migration, then run 'make sqlc'." >&2
        exit 2
        ;;
esac

# GOEN: templ writes these from the .templ source next to them.
if [[ "$relative_path" == *_templ.go ]]; then
    echo "BLOCKED: $relative_path is generated by templ. Edit the .templ file and run 'make gen'." >&2
    exit 2
fi

# GOEN: the design system is vendored verbatim from the koopa.dev project.
# Patching it here means the next re-vendor silently reverts the fix.
if [[ "$relative_path" == assets/css/ds/* ]]; then
    echo "BLOCKED: $relative_path is vendored from the koopa.dev design system. Fix it upstream and re-vendor; style its classes from assets/css/app/app.css instead." >&2
    exit 2
fi

# Block edits to files with generated header
if [[ -f "$file_path" ]] && head -3 "$file_path" | grep -q "Code generated.*DO NOT EDIT"; then
    echo "BLOCKED: This file is generated code (DO NOT EDIT header). Modify the source and re-generate." >&2
    exit 2
fi

exit 0
